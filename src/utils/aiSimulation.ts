import { Case, CaseEvent, Evidence } from '../types';

export interface AISuggestionResponse {
  isDemonstrationMode: boolean;
  generatedAt: string;
  summary: string;
  missingInformation: string[];
  suggestedSteps: {
    title: string;
    action: string;
    rationale: string;
    sourceTitle?: string;
    sourceUrl?: string;
    sourceLastChecked?: string;
  }[];
  draftFollowUpMessage: {
    subject: string;
    body: string;
    recipientType: string;
    cautionNote: string;
  };
  recommendedQuestions: string[];
  timelineAnalysis: string;
  disclaimer: string;
}

export function generateAIDemoAssistant(
  caseData: Case,
  events: CaseEvent[],
  evidenceList: Evidence[]
): AISuggestionResponse {
  const hasReceipt = evidenceList.some(e => e.category === 'receipt');
  const hasJobSheet = evidenceList.some(e => e.category === 'warranty_card');
  const missingInfo: string[] = [];

  if (!caseData.order_reference) {
    missingInfo.push('Reference or Order/Ticket ID is missing. Adding this helps the organisation trace the transaction.');
  }
  if (caseData.category === 'refund_follow_up' && !events.some(e => e.description.toLowerCase().includes('arn') || e.description.toLowerCase().includes('utr'))) {
    missingInfo.push('Bank Transaction Reference Number (ARN / UTR). This is required by your bank to trace a pending refund.');
  }
  if (caseData.category === 'warranty_repair' && !hasJobSheet) {
    missingInfo.push('Authorized Service Centre Job Sheet / Work Order number with technician defect remarks.');
  }
  if (!hasReceipt && evidenceList.length === 0) {
    missingInfo.push('Copy of the original invoice, booking confirmation, or payment deduction screenshot.');
  }
  if (events.length <= 1) {
    missingInfo.push('Specific date and method of initial customer support contact (e.g. chat transcript, email header).');
  }

  let draftSubject = `Inquiry regarding ${caseData.category.replace('_', ' ')} - Ref: ${caseData.order_reference || 'Case #' + caseData.id.slice(-6)}`;
  let draftBody = '';
  let rationale = '';
  let sourceTitle = 'Department of Consumer Affairs Process Guidance';
  let sourceUrl = 'https://consumerhelpline.gov.in/';
  let sourceLastChecked = '2025-01-15';

  if (caseData.category === 'delayed_delivery') {
    draftSubject = `URGENT: Delivery Status Update Required - Order Ref ${caseData.order_reference || '[Order ID]'}`;
    draftBody = `Dear ${caseData.organisation || 'Support Team'},

I am writing regarding my order (Ref: ${caseData.order_reference || '[Enter Order Reference]'}), placed on ${caseData.issue_started_at || '[Order Date]'}.

The shipment is currently delayed beyond the originally confirmed delivery window. Courier tracking currently indicates that the consignment has been stalled without progress.

Timeline Summary:
• Order placed / initial date: ${caseData.issue_started_at}
• Previous communication: ${events.length > 1 ? events[events.length - 1].description : 'Prior customer support inquiry submitted.'}

Could you please provide:
1. An updated, confirmed dispatch/delivery date within 48 hours, OR
2. If delivery cannot be fulfilled promptly, confirmation of order cancellation and full refund to the original payment method.

I appreciate your prompt assistance in resolving this matter.

Regards,
[Your Name]
[Contact Number]`;
    rationale = 'Rule 5(4) of the Consumer Protection (E-Commerce) Rules, 2020 requires grievance officers to acknowledge complaints within 48 hours and provide redressal timelines.';
    sourceTitle = 'Consumer Protection (E-Commerce) Rules, 2020';
    sourceUrl = 'https://consumeraffairs.nic.in/';
  } else if (caseData.category === 'refund_follow_up') {
    draftSubject = `Request for Bank ARN / UTR Reference for Refund - Order Ref ${caseData.order_reference || '[Order ID]'}`;
    draftBody = `Dear ${caseData.organisation || 'Accounts Team'},

I am writing regarding the pending refund for reference ${caseData.order_reference || '[Order ID]'}, initiated following the cancellation/return on ${caseData.issue_started_at}.

To date, the refund has not settled into my bank account. To enable my bank to trace and reconcile the incoming credit, please provide the standard electronic banking reference:
1. Acquirer Reference Number (ARN) for card reversal, or
2. Unique Transaction Reference (UTR) for UPI/IMPS transfer.

If the reversal has not yet been triggered through your payment gateway, please confirm the revised processing date.

Thank you for your cooperation.

Sincerely,
[Your Name]
[Contact Number]`;
    rationale = 'Banks cannot investigate uncredited merchant refunds without the 23-digit ARN or 12-digit UTR reference generated by the acquiring bank.';
    sourceTitle = 'Reserve Bank of India (RBI) Electronic Banking Guidelines';
    sourceUrl = 'https://www.rbi.org.in/';
  } else if (caseData.category === 'warranty_repair') {
    draftSubject = `Warranty Service Escalation: Status of Job Sheet ${caseData.order_reference || '[Job Sheet #]'}`;
    draftBody = `Dear ${caseData.organisation || 'Customer Relations Team'},

I am writing to escalate the delay regarding the repair of my device under warranty, deposited at your authorized service centre on ${caseData.issue_started_at} under Job Sheet ${caseData.order_reference || '[Job Sheet #]'}.

The device has remained with the service facility beyond the standard service turnaround time. The latest update indicated spare parts are unavailable with no committed date.

Under standard manufacturer warranty terms and fair service practice, please confirm:
1. The firm completion and handover date for the repaired unit, OR
2. Options for authorized unit replacement or commercial credit voucher if genuine spare parts are unavailable.

I look forward to your written response within 3 business days.

Regards,
[Your Name]
[Contact Details]`;
    rationale = 'Section 2(11) of the Consumer Protection Act, 2019 addresses deficiency in service when authorized warranty commitments are subjected to unreasonable delay without relief.';
    sourceTitle = 'Consumer Protection Act, 2019';
    sourceUrl = 'https://consumeraffairs.nic.in/acts-and-rules/consumer-protection';
  } else {
    draftSubject = `Follow-Up regarding ${caseData.title} - Reference ${caseData.order_reference || '[Reference #]'}`;
    draftBody = `Dear ${caseData.organisation || 'Support Team'},

I am following up regarding the unresolved matter concerning "${caseData.title}", first reported on ${caseData.issue_started_at}.

Issue Summary:
${caseData.description}

Current Status:
We have recorded ${events.length} timeline event(s). A satisfactory resolution has not yet been achieved.

I kindly request that you review the attached chronology and provide an updated resolution plan within 3 business days.

Thank you for your attention to this issue.

Sincerely,
[Your Name]
[Contact Information]`;
    rationale = 'Establishing a polite, factual written record with specific deadlines is standard best practice for resolving commercial grievances.';
  }

  return {
    isDemonstrationMode: true,
    generatedAt: new Date().toISOString(),
    summary: `Case involves ${caseData.organisation || 'the organization'} regarding ${caseData.category.replace('_', ' ')}. Active since ${caseData.issue_started_at || 'initial report'}, with ${events.length} recorded timeline events and ${evidenceList.length} evidence attachments.`,
    missingInformation: missingInfo,
    suggestedSteps: [
      {
        title: 'Review Internal Escalation Hierarchy',
        action: `Identify the formal Grievance Redressal Officer or Escalation Manager email for ${caseData.organisation || 'the company'}.`,
        rationale: rationale,
        sourceTitle: sourceTitle,
        sourceUrl: sourceUrl,
        sourceLastChecked: sourceLastChecked
      },
      {
        title: 'Send Factual Follow-Up with Firm Timeframe',
        action: 'Review and send the polite draft message below directly through the official support channel. CLEARPATH will not send this automatically.',
        rationale: 'Formal written notice prevents verbal miscommunication and provides verifiable documentation.',
        sourceTitle: 'National Consumer Helpline Process Guide',
        sourceUrl: 'https://consumerhelpline.gov.in/',
        sourceLastChecked: '2025-01-15'
      },
      {
        title: 'Set a 72-Hour Calendar Reminder',
        action: 'Schedule a reminder in CLEARPATH to verify receipt or prepare next stage escalation if no written answer is provided.',
        rationale: 'Tracking response deadlines ensures cases do not stall indefinitely.',
      }
    ],
    draftFollowUpMessage: {
      subject: draftSubject,
      body: draftBody,
      recipientType: 'Customer Support Escalation / Grievance Officer',
      cautionNote: 'Review and customize the message before sending. Replace all bracketed items. CLEARPATH never sends emails or messages on your behalf.'
    },
    recommendedQuestions: [
      'What is the unique internal docket / escalation reference number for this ticket?',
      'Who is the assigned senior case manager handling this file?',
      'What is the definitive turnaround timeframe (SLA) for the next status update?',
      caseData.category === 'refund_follow_up' ? 'Can you provide the 23-digit ARN (for card) or 12-digit UTR (for bank/UPI)?' : 'If this cannot be resolved within 3 business days, what is the next escalation level?'
    ],
    timelineAnalysis: `The timeline contains ${events.length} logged event(s). The most recent action was on ${events.length > 0 ? events[events.length - 1].event_date : caseData.issue_started_at}. Keeping each step documented ensures a complete audit trail if formal grievance reporting is later required.`,
    disclaimer: 'CLEARPATH AI Assistant provides structured informational assistance and communication templates based on published consumer guidelines. It does NOT provide legal advice, does not file complaints, and does not guarantee outcomes. Information last verified against official guidelines in January 2025.'
  };
}
